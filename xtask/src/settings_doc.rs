//! `docs/settings-reference.md`, generated from the settings schema with
//! the theme list, the color roles and the column kinds. `cargo xtask
//! regen` writes it and `cargo xtask regen --check` checks it; nobody
//! edits it by hand.

use diroxide_app::settings::{
    BUILTIN_SPLIT_PRESETS, ColumnKind, DRIVE_KINDS, PanelRole, SCHEMA, SettingGroup, SettingKind,
    theme_names,
};

/// The page, relative to the workspace root.
pub const PAGE: &str = "docs/settings-reference.md";

/// The page's text.
pub fn generate() -> String {
    let mut page = String::new();
    page.push_str("# Settings reference\n\n");
    page.push_str("This page is generated by `cargo xtask regen` from the settings schema. Do not edit it by hand; change the schema instead. The settings guide says how to choose them.\n\n");
    page.push_str("The settings live in `config.toml` in the config folder: `%APPDATA%\\diroxide` on Windows, `~/Library/Application Support/diroxide` on macOS, and `~/.config/diroxide` on Linux, or a `config` folder beside the program with `--portable`. A missing setting takes its default. A key with a dot belongs to a table: `sort.key` is `key` under `[sort]`. A value diroxide cannot use keeps its default and is said in words at the start; a key it does not know is kept as it is. diroxide writes the file only when you change a setting in the program, one value at a time, so your comments stay.\n\n");
    page.push_str(
        "Settings marked as coming with a later alpha are kept now and do nothing yet.\n",
    );
    for group in SettingGroup::ALL {
        page.push_str(&format!("\n## {}\n", group.title()));
        for info in SCHEMA.iter().filter(|s| s.group == group) {
            page.push_str(&format!("\n### {}\n\n", info.key));
            page.push_str(&format!("{}. {}\n\n", info.name, info.help));
            page.push_str(&format!("- Holds: {}.\n", info.kind.words()));
            if info.kind == SettingKind::SplitPresets {
                page.push_str("- Default: the built-in presets, each with its source:\n");
                for builtin in &BUILTIN_SPLIT_PRESETS {
                    let preset = builtin.preset();
                    page.push_str(&format!(
                        "  - {}. {}. {}.\n",
                        preset.row_text(),
                        preset.details_line(),
                        builtin.source
                    ));
                }
                page.push_str("- Add your own, after the built-in ones:\n\n```toml\n[[split_presets]]\nname = \"Zip disk\"\nbytes = 100663296\n```\n\n");
            } else {
                page.push_str(&format!("- Default: `{}`.\n", info.default));
            }
            if let SettingKind::Choice(choices) = info.kind {
                for choice in choices {
                    page.push_str(&format!("- `{}`: {}.\n", choice.value, choice.words));
                }
            }
            if info.kind == SettingKind::DriveKinds {
                page.push_str(&format!("- Drive kinds: {}.\n", DRIVE_KINDS.join(", ")));
            }
            if info.arrives.is_some() {
                page.push_str("- Comes with a later alpha.\n");
            }
        }
    }
    page.push_str("\n## Themes\n\nThe built-in themes, for the `theme` setting. Your own theme files go in the `themes` folder in the config folder and are listed after these.\n\n");
    for name in theme_names() {
        page.push_str(&format!("- `{name}`\n"));
    }
    page.push_str("\n## Color roles\n\nThe roles the `[colors]` table can color, each as `role = \"#rrggbb\"`. Every role also keeps its bold, underline, italic or reverse, so nothing depends on color alone, and each color is checked for contrast.\n\n");
    for role in PanelRole::ALL {
        page.push_str(&format!("- `{}`: {}.\n", role.key(), role.label()));
    }
    page.push_str("\n## Columns\n\nThe columns the `columns` setting can list, in the order you want them said after each name.\n\n");
    for kind in ColumnKind::ALL {
        page.push_str(&format!("- `{}`: {}.\n", kind.name(), kind.label()));
    }
    page.push_str(
        "\n## See also\n\n- [Keyboard](keyboard.md)\n- [The documentation index](README.md)\n",
    );
    page
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_setting_is_on_the_page_without_tables() {
        let page = generate();
        for info in SCHEMA.iter() {
            assert!(
                page.contains(&format!("\n### {}\n", info.key)),
                "{}",
                info.key
            );
        }
        assert!(page.contains("- `galaxy`\n"));
        assert!(page.contains("- `focused_row`: focused row.\n"));
        assert!(page.contains("- `octal`: Octal mode.\n"));
        // Every alpha.3 setting is live (W3a); the plugins come next.
        assert!(page.contains("- Comes with alpha.4.\n"));
        assert!(page.contains("\n### archives.max_entries\n"));
        assert!(page.contains("  - GitHub file limit, 100 MiB. Parts of 104,857,600 bytes. 104,857,600 bytes: GitHub blocks"));
        assert!(
            !page.contains("bytes = 18000000"),
            "no TOML table on one line"
        );
        assert!(!page.contains('|'));
        assert!(page.ends_with("(README.md)\n"));
    }
}
