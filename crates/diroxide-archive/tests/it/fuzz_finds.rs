/// `archive_xz`'s find (base64 `/Td6WFoAAATm1rRGAKiG//N1fQEAAAQAWg==`): a
/// stream header, then an index whose record count, 31,650,202,408, made
/// `lzma-rust2` 0.21 ask for 506 GB before it read a record.
pub const XZ_INDEX_COUNT: [u8; 25] = [
    0xFD, 0x37, 0x7A, 0x58, 0x5A, 0x00, 0x00, 0x04, 0xE6, 0xD6, 0xB4, 0x46, 0x00, 0xA8, 0x86, 0xFF,
    0xF3, 0x75, 0x7D, 0x01, 0x00, 0x00, 0x04, 0x00, 0x5A,
];

/// [`XZ_INDEX_COUNT`] made whole: the same stream header and record
/// count, the index's CRC and a footer that are right, so only the count
/// is wrong, and nothing but the count check refuses it.
pub fn xz_index_count_whole() -> Vec<u8> {
    let mut out = XZ_INDEX_COUNT[..12].to_vec();
    let mut index = XZ_INDEX_COUNT[12..18].to_vec();
    index.resize(8, 0);
    index.extend_from_slice(&crc32fast::hash(&index).to_le_bytes());
    out.extend_from_slice(&index);
    let mut tail = 2u32.to_le_bytes().to_vec();
    tail.extend_from_slice(&XZ_INDEX_COUNT[6..8]);
    out.extend_from_slice(&crc32fast::hash(&tail).to_le_bytes());
    out.extend_from_slice(&tail);
    out.extend_from_slice(b"YZ");
    out
}

#[test]
fn the_7z_find_replays_and_is_refused_in_words() {
    fuzzing::sevenz(&SEVENZ_COUNTS);
    let world = World::plain();
    let place = world.put("found.7z", &SEVENZ_COUNTS[9..]);
    let error = world.rows(&place.into_archive()).unwrap_err();
    assert_eq!(
        error,
        "it is damaged: its header's stream counts are too large"
    );
}

#[test]
fn the_xz_find_replays_and_is_refused_on_both_paths() {
    // The target bodies: the xz checks and decode, and the tar stream.
    fuzzing::xz(&XZ_INDEX_COUNT);
    let mut stream = vec![1u8];
    stream.extend_from_slice(&XZ_INDEX_COUNT);
    fuzzing::stream(&stream);
    let whole = xz_index_count_whole();
    fuzzing::xz(&whole);
    let mut stream = vec![1u8];
    stream.extend_from_slice(&whole);
    fuzzing::stream(&stream);
    // The provider: a plain .xz and a tar.xz, refused at open, in words.
    let world = World::plain();
    for name in ["found.xz", "found.tar.xz"] {
        let place = world.put(name, &XZ_INDEX_COUNT);
        let error = world.rows(&place.into_archive()).unwrap_err();
        assert_eq!(
            error,
            "it is damaged: it ends without a stream footer: \
             it is cut short or has data after its end",
            "{name}"
        );
    }
    for name in ["whole.xz", "whole.tar.xz"] {
        let place = world.put(name, &whole);
        let error = world.rows(&place.into_archive()).unwrap_err();
        assert_eq!(error, "it is damaged: its index is damaged", "{name}");
    }
}
