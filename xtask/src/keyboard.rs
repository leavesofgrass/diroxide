//! `cargo xtask keyboard`: writes `docs/keyboard.md` from the command
//! catalog, the keymap's defaults and the three key tables, as two lists:
//! the terminal's keys and the window's, and one sheet per keymap preset,
//! `docs/keyboard-NAME.md`, with what the preset changes, key first on
//! every line, and the key sequences its source uses, held back. The pages
//! are generated; nobody edits them by hand. `cargo xtask regen` writes
//! them too.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use diroxide_app::commands::{CATALOG, CommandInfo};
use diroxide_app::config::{KeymapConfig, SingleLetters};
use diroxide_app::keymap::presets::{self, Preset};
use diroxide_app::keymap::tables::{
    TerminalKind, reserved_table, screen_reader_table, terminal_entry, terminal_table,
};
use diroxide_app::keymap::{Keymap, Platform, written};
use diroxide_app::menu::{ItemAction, Menus};
use diroxide_core::{Key, KeyColumn, Layer};

/// The page, relative to the workspace root.
pub const PAGE: &str = "docs/keyboard.md";

/// The platform the page names keys for: Alt, not Option.
const NAMES: Platform = Platform::Windows;

fn layer_heading(layer: Layer) -> &'static str {
    match layer {
        Layer::Global => "Everywhere",
        Layer::Panel => "In a panel",
        Layer::List => "In any list",
        Layer::Viewer => "In the viewer",
        Layer::Preview => "In the preview",
        Layer::Dialog => "In a question",
    }
}

fn keys_of(keymap: &Keymap, info: &CommandInfo) -> Vec<Key> {
    keymap
        .bindings()
        .iter()
        .filter(|b| b.layer == info.layer && b.command == info.id)
        .map(|b| b.key)
        .collect()
}

fn line(keys: &[Key], info: &CommandInfo) -> String {
    let keys: Vec<String> = keys.iter().map(|k| written(k, NAMES)).collect();
    format!(
        "- {}: {}. {} ({})",
        keys.join(" or "),
        info.name,
        info.help,
        info.id
    )
}

fn column_section(page: &mut String, column: KeyColumn) {
    let keymap = Keymap::defaults_for(column);
    for layer in Layer::ALL {
        let lines: Vec<String> = CATALOG
            .iter()
            .filter(|info| info.layer == layer)
            .filter_map(|info| {
                let keys = keys_of(&keymap, info);
                (!keys.is_empty()).then(|| line(&keys, info))
            })
            .collect();
        if !lines.is_empty() {
            page.push_str(&format!("\n### {}\n\n", layer_heading(layer)));
            for l in lines {
                page.push_str(&l);
                page.push('\n');
            }
        }
    }
    let keyless: Vec<String> = CATALOG
        .iter()
        .filter(|info| keys_of(&keymap, info).is_empty())
        .map(|info| format!("- {}. {} ({})", info.name, info.help, info.id))
        .collect();
    if !keyless.is_empty() {
        page.push_str("\n### By the palette and the menus\n\n");
        for l in keyless {
            page.push_str(&l);
            page.push('\n');
        }
    }
}

fn capitalized(text: &str) -> String {
    let mut chars = text.chars();
    match chars.next() {
        Some(c) => c.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

/// The menu and item that reach a command, in words: "Edit menu, Paste".
fn sure_way(menus: &Menus, info: &CommandInfo) -> String {
    for menu in menus.menus() {
        if menu
            .items
            .iter()
            .any(|i| i.action == ItemAction::Command(info.id.clone()))
        {
            let parent = menus.bar().find(|bar| {
                bar.items
                    .iter()
                    .any(|i| i.action == ItemAction::Submenu(menu.id.clone()))
            });
            return match parent {
                Some(parent) => format!(
                    "{} menu, {} submenu, {}",
                    parent.title, menu.title, info.name
                ),
                None => format!("{} menu, {}", menu.title, info.name),
            };
        }
    }
    "the command palette".to_owned()
}

/// The page's text.
pub fn generate() -> String {
    let mut page = String::new();
    page.push_str("# Keyboard\n\n");
    page.push_str("This page is generated by `cargo xtask keyboard` from the command catalog, the keymap's defaults and the key tables. Do not edit it by hand; change the catalog or the tables instead.\n\n");
    page.push_str("Each line gives the key first, then the command, what it does, and its id in parentheses. A key is one key with its modifiers; there are no key sequences. Insert is never used, because it is the screen readers' key. Change any key in `keymap.toml` in the config folder; diroxide writes the built-in keys beside it as `keymap-defaults.toml`. The `single_letters` setting turns keys without Control or Alt off.\n\n");
    page.push_str("The command palette reaches every command by name: Ctrl+P in a terminal, Ctrl+Shift+P or Ctrl+P in the window. The menus are the sure way where a terminal does not pass a key: F9, or Alt with a menu's letter.\n");
    page.push_str("\n## In a terminal\n");
    column_section(&mut page, KeyColumn::Terminal);
    page.push_str("\n## In the window\n\n");
    page.push_str("The window arrives in a later alpha; these are its keys. On macOS the window uses Command where this list says Ctrl, and leaves Ctrl+F3 to Ctrl+F7 and Ctrl+Space to the system; the Sort list, the View menu and the palette sort there.\n");
    column_section(&mut page, KeyColumn::Window);

    let menus = Menus::builtin();
    let terminal = Keymap::defaults_for(KeyColumn::Terminal);
    page.push_str("\n## Keys a terminal may keep\n\n");
    page.push_str("These keys of the terminal list work in most terminals, but a terminal program may keep them or send another key. Each one's command is also in a menu, the sure way.\n\n");
    for info in CATALOG.iter() {
        for key in keys_of(&terminal, info) {
            let Some(row) = terminal_entry(&key) else {
                continue;
            };
            let who = match row.kind {
                TerminalKind::Program => format!("{} keeps it; {}", row.program, row.why),
                TerminalKind::Differs => capitalized(&row.why),
                TerminalKind::Unsafe => continue,
            };
            page.push_str(&format!(
                "- {} for {}: {}. Sure way: {}.\n",
                written(&key, NAMES),
                info.name,
                who,
                sure_way(&menus, info)
            ));
        }
    }
    page.push_str("\n## Keys never used in a terminal\n\n");
    for row in terminal_table()
        .iter()
        .filter(|r| r.kind == TerminalKind::Unsafe)
    {
        let mut names: Vec<String> = row.keys.iter().map(|k| written(k, NAMES)).collect();
        if let Some(pattern) = row.pattern {
            names.push(pattern.words().to_owned());
        }
        page.push_str(&format!("- {}: {}.\n", names.join(", "), row.why));
    }
    page.push_str("\n## Keys the screen readers keep\n\n");
    page.push_str("diroxide binds none of these. A keypad key works under a screen reader only with Num Lock on, so it is never a command's only key.\n\n");
    for row in screen_reader_table() {
        let named_for = row.platform.unwrap_or(NAMES);
        let mut names: Vec<String> = row.keys.iter().map(|k| written(k, named_for)).collect();
        if let Some(pattern) = row.pattern {
            names.push(pattern.words().to_owned());
        }
        let platform = match row.platform {
            Some(Platform::MacOs) => " On macOS.",
            Some(Platform::Other) => " On Linux.",
            Some(Platform::Windows) => " On Windows.",
            None => "",
        };
        page.push_str(&format!(
            "- {}: {}, {}.{platform}\n",
            names.join(", "),
            row.readers,
            row.purpose
        ));
    }
    page.push_str("\n## Kept for later alphas\n\n");
    for row in reserved_table() {
        let names: Vec<String> = row.keys.iter().map(|k| written(k, NAMES)).collect();
        let column = match row.column {
            None => String::new(),
            Some(KeyColumn::Terminal) => ", in a terminal".to_owned(),
            Some(KeyColumn::Window) => ", in the window".to_owned(),
        };
        page.push_str(&format!(
            "- {}: {}, coming later{column}.\n",
            names.join(" or "),
            row.name
        ));
    }
    page.push_str("\n## See also\n\n");
    for preset in presets::presets().iter().filter(|p| !p.is_default()) {
        page.push_str(&format!(
            "- [The {} preset]({})\n",
            preset.name,
            sheet_file(preset)
        ));
    }
    page.push_str(
        "- [Settings reference](settings-reference.md)\n- [The documentation index](README.md)\n",
    );
    page
}

/// A preset's sheet, relative to `docs/`: `keyboard-total-commander.md`.
pub fn sheet_file(preset: &Preset) -> String {
    format!("keyboard-{}.md", preset.id)
}

/// A preset's sheet, relative to the workspace root.
pub fn sheet_page(preset: &Preset) -> String {
    format!("docs/{}", sheet_file(preset))
}

/// A key sequence as a sheet writes it, each key named: "Ctrl+X C".
fn sequence_words(text: &str) -> String {
    text.split_whitespace()
        .map(|part| match Key::parse(part) {
            Ok(key) => written(&key, NAMES),
            Err(_) => part.to_owned(),
        })
        .collect::<Vec<_>>()
        .join(" ")
}

/// The lines a preset changes in one column, by layer, key first: "-
/// Shift+F6: Rename. Was F2. (file.rename)".
fn changes(page: &mut String, lines: &KeymapConfig, column: KeyColumn, platform: Platform) {
    let defaults = Keymap::defaults_for(column).for_platform(platform);
    for layer in Layer::ALL {
        let here: Vec<_> = lines
            .overrides
            .iter()
            .filter(|l| l.column == column && l.layer == layer)
            .collect();
        if here.is_empty() {
            continue;
        }
        page.push_str(&format!("\n### {}\n\n", layer_heading(layer)));
        for line in here {
            let name = diroxide_app::commands::name_of(&line.command);
            let keys: Vec<String> = line.keys.iter().map(|k| written(k, platform)).collect();
            let was: Vec<String> = defaults
                .keys_in(layer, &line.command)
                .iter()
                .map(|k| written(k, platform))
                .collect();
            let now = if keys.is_empty() {
                "No key".to_owned()
            } else {
                keys.join(" or ")
            };
            let before = if was.is_empty() {
                "No key before".to_owned()
            } else {
                format!("Was {}", was.join(" or "))
            };
            page.push_str(&format!("- {now}: {name}. {before}. ({})\n", line.command));
        }
    }
}

/// A preset's sheet.
pub fn sheet(preset: &Preset) -> String {
    let mut page = String::new();
    page.push_str(&format!("# Keyboard: the {} preset\n\n", preset.name));
    page.push_str(&format!(
        "This page is generated by `cargo xtask keyboard` from `crates/diroxide-app/keys/presets/{}.toml`. Do not edit it by hand; change the preset file instead.\n\n",
        preset.id
    ));
    page.push_str(&format!("{}\n\n", preset.description));
    page.push_str(&format!(
        "Choose it in the Keys list (its first row, Choose a preset), with Key presets in the palette or in the Tools menu's Keys submenu, or from a shell with `diro keys preset {}`. Your own keys in `keymap.toml` stay on top of it, and every key it does not list is the one on [the keyboard page](keyboard.md). Each line below gives the key first, then the command, the key it replaces, and the command's id.\n\n",
        preset.id
    ));
    page.push_str(match preset.letters {
        SingleLetters::Commands => "Single letters run commands with this preset: typing no longer jumps to names, and the slash opens the filter. Choosing it turns type-ahead off; choosing another preset turns it back on.\n",
        _ => "Single letters still jump to names with this preset.\n",
    });
    page.push_str(&format!("\nIts keys come from {}.\n", preset.source));
    page.push_str("\n## In a terminal\n");
    changes(&mut page, &preset.lines, KeyColumn::Terminal, NAMES);
    page.push_str("\n## In the window\n");
    changes(&mut page, &preset.lines, KeyColumn::Window, NAMES);
    if !preset.macos.overrides.is_empty() {
        page.push_str("\n## On macOS, in the window\n\nOn macOS the window has these keys as well, the Finder's.\n");
        changes(&mut page, &preset.macos, KeyColumn::Window, Platform::MacOs);
    }
    if !preset.held_back.is_empty() {
        page.push_str("\n## Held back\n\n");
        page.push_str("These keys of the source are two keys in a row, which diroxide does not use: a key here is one key with its modifiers. The command each would run is reached by its own key, the menus or the palette.\n\n");
        for held in &preset.held_back {
            page.push_str(&format!(
                "- {}: {}.\n",
                sequence_words(&held.keys),
                held.command
            ));
        }
    }
    page.push_str(
        "\n## See also\n\n- [Every key](keyboard.md)\n- [The documentation index](README.md)\n",
    );
    page
}

/// Every preset sheet: its page, from the root, and its text.
pub fn sheets() -> Vec<(String, String)> {
    presets::presets()
        .iter()
        .filter(|p| !p.is_default())
        .map(|p| (sheet_page(p), sheet(p)))
        .collect()
}

/// The page and every preset sheet: each one's path from the root and its
/// text.
pub fn all_pages() -> Vec<(String, String)> {
    let mut pages = vec![(PAGE.to_owned(), generate())];
    pages.extend(sheets());
    pages
}

/// Writes the page and the preset sheets.
pub fn write(root: &Path) -> Result<bool> {
    for (page, text) in all_pages() {
        fs::write(root.join(&page), text)
            .with_context(|| format!("{page} could not be written"))?;
        println!("keyboard: wrote {page}.");
    }
    Ok(true)
}

/// Checks that the page and the preset sheets on disk are the generated
/// ones.
pub fn check(root: &Path) -> Result<bool> {
    let stale: Vec<String> = all_pages()
        .into_iter()
        .filter(|(page, text)| fs::read_to_string(root.join(page)).unwrap_or_default() != *text)
        .map(|(page, _)| page)
        .collect();
    if stale.is_empty() {
        println!("keyboard: Pass. {PAGE} and the preset sheets are current.");
        Ok(true)
    } else {
        println!(
            "keyboard: Fail. Out of date: {}; run cargo xtask keyboard.",
            stale.join(", ")
        );
        Ok(false)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_page_puts_keys_first_and_names_every_command() {
        let page = generate();
        assert!(page.contains("\n- F5: Copy to other panel. "));
        assert!(page.contains("\n- Ctrl+Q: Quit. Leaves diroxide. (app.quit)\n"));
        assert!(page.contains("\n## In a terminal\n"));
        assert!(page.contains("\n## In the window\n"));
        assert!(page.contains("\n### In any list\n"));
        assert!(page.contains("- Ctrl+V for Paste: Windows Terminal keeps it"));
        assert!(page.contains("Sure way: Edit menu, Paste."));
        assert!(page.contains("Sure way: View menu, Sort submenu, Sort by modified."));
        // Ctrl+F is bound to Find files since alpha.3 (W3a); Ctrl+T stays
        // kept for tabs.
        assert!(page.contains("- Ctrl+T: New tab, coming later.\n"));
        assert!(page.contains("- Ctrl+F: Find files. "));
        for info in CATALOG.iter() {
            assert!(page.contains(&format!("({})", info.id)), "{}", info.id);
        }
        assert!(!page.contains('|'), "no tables in user docs");
        assert!(page.contains("\n## See also\n"));
        assert!(page.contains("- [The Total Commander preset](keyboard-total-commander.md)\n"));
    }

    #[test]
    fn each_preset_has_a_sheet_with_its_keys_first() {
        let sheets = sheets();
        assert_eq!(sheets.len(), presets::presets().len() - 1);
        let tc = presets::preset("total-commander").unwrap();
        let text = sheet(tc);
        assert!(text.starts_with("# Keyboard: the Total Commander preset\n"));
        assert!(
            text.contains("\n- Shift+F6: Rename. Was F2. (file.rename)\n"),
            "{text}"
        );
        assert!(
            text.contains("\n- No key: Next selected. Was Ctrl+Down. (select.next)\n"),
            "{text}"
        );
        assert!(text.contains("\n## In the window\n"));
        let mc = sheet(presets::preset("midnight-commander").unwrap());
        assert!(mc.contains("\n## Held back\n"));
        assert!(
            mc.contains("\n- Ctrl+X C: Change permissions, and the owner in its dialog.\n"),
            "{mc}"
        );
        let finder = sheet(presets::preset("explorer-finder").unwrap());
        assert!(finder.contains("\n## On macOS, in the window\n"));
        assert!(finder.contains("Cmd+I"), "{finder}");
        let vim = sheet(presets::preset("vim-style").unwrap());
        assert!(vim.contains("Single letters run commands with this preset"));
        for (_, text) in &sheets {
            assert!(!text.contains('|'), "no tables in user docs");
            assert!(text.ends_with("- [The documentation index](README.md)\n"));
            for line in text.lines().filter(|l| l.starts_with("- ")) {
                assert!(!line.starts_with("- ("), "the key comes first: {line}");
            }
        }
    }
}
