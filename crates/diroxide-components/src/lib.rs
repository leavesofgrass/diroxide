//! Optional components (plan section 5.14): the plugins, helper programs
//! and data packs diroxide can use but does not ship, and the one way
//! they are fetched, checked, installed and removed.
//!
//! The model is textweaver's components crate, the owner's own code,
//! relicensed under answer 3 (R22 section 6.1): each [`Component`] has an
//! id, a title, a kind, a version, a license, the features that need it,
//! a folder under the components folder, and its files, each pinned by
//! size and SHA-256 ([`FilePin`]). The pins are the contract, not the
//! addresses: a file whose size or hash does not match is refused,
//! whoever served it.
//!
//! - [`Component::status_in`] says from the sizes whether a component is
//!   installed; [`Component::verify_in`] hashes every file.
//! - [`Component::removal_in`] lists every path Remove would take away,
//!   and [`Removal::run`] removes those and nothing else: a file the owner
//!   put in the folder stays.
//! - [`Manifest`] is the list, `components.toml`: the public one is
//!   generated by `cargo xtask components` from the real assets and
//!   embedded in the binary ([`Manifest::embedded`]); a source folder's
//!   list may add components and never change a known one's pins.
//! - A [`Fetcher`] opens an address from a byte: [`LocalFetcher`] reads a
//!   source folder; [`StandardFetcher`] sends an `https` address to the
//!   built-in client (the `fetch` feature), then curl, then wget from
//!   PATH, each with the neutral [`USER_AGENT`] and nothing else about the
//!   owner.
//!
//! - The [`Downloader`] fetches a component's files for this computer
//!   from the owner's own source, then the public address, through a
//!   `.part` file per file with a note of where its bytes came from;
//!   Escape stops it and the next try resumes; nothing moves into the
//!   component's folder before every file matched its pin. It takes a
//!   [`Consent`], which only the owner's yes makes.
//!
//! - An `unpack` component's archives are unpacked through
//!   `diroxide-archive` with plain names only, no links, within the list's
//!   `unpacked_size`, and a receipt takes each archive's place
//!   ([`unpack_in`]); [`install_from`] installs from a zip file or a folder
//!   with the same pins, for a computer without a network.
//!
//! Nothing here asks the owner: the app and `diro components` say the
//! size and the license and wait for a yes before anything is fetched.

