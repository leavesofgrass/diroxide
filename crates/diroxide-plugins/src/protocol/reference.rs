//! The protocol reference, `docs/dev/plugin-protocol.md`, generated from
//! [`super::methods::ALL`] and [`super::ErrorKind::ALL`]. `cargo xtask
//! regen` writes it and `cargo xtask regen --check` checks it; nobody
//! edits it by hand.

use super::methods::{self, ALL, Area, Call};
use super::{ErrorKind, MAX_LINE_BYTES, MAX_LINE_BYTES_LIMIT, PROTOCOL};

/// The page, relative to the workspace root.
pub const PAGE: &str = "docs/dev/plugin-protocol.md";

/// The page's text.
pub fn page() -> String {
    let (requests, notifications) = methods::counts();
    let mut out = String::new();
    out.push_str("# Plugin protocol reference\n\n");
    out.push_str(
        "This page is generated by `cargo xtask regen` from the methods module of \
         `diroxide-plugins` (`protocol::methods`). Do not edit it by hand; change the \
         module instead. The reasons behind each rule are in ADR-0006 and in the plan, \
         section 5.8.\n\n",
    );
    out.push_str(&format!(
        "Protocol {PROTOCOL} has {requests} requests and {notifications} notifications. \
         Within protocol {PROTOCOL} only additions are made, and every method is optional: \
         a host method the plugin did not declare in its manifest and confirm in \
         `initialize` is never called, and a service the host did not offer in \
         `host_capabilities` is never called by the plugin.\n"
    ));

    out.push_str("\n## Framing\n\n");
    out.push_str(
        "- One JSON-RPC 2.0 message per line, UTF-8 without a byte order mark, in both \
         directions. The host ends lines with `\\n` and accepts `\\r\\n`.\n",
    );
    out.push_str(&format!(
        "- The longest line is {} MiB by default; a plugin may ask for up to {} MiB in its \
         manifest. The reader enforces the limit while reading; a longer line is refused, \
         and the next line is still read.\n",
        MAX_LINE_BYTES / (1024 * 1024),
        MAX_LINE_BYTES_LIMIT / (1024 * 1024)
    ));
    out.push_str(
        "- A line that does not start with `{` after spaces is stray output: logged, \
         counted and never answered. A line that starts with `{` and does not parse, or is \
         not valid UTF-8, is answered with -32700 and a null id.\n",
    );
    out.push_str("- Batches (JSON arrays) are refused with -32600.\n");
    out.push_str(
        "- Standard error is free text for the plugin's log, never the screen.\n\
         - A plugin flushes after every message.\n",
    );

    out.push_str("\n## Envelopes\n\n");
    out.push_str(
        "- A request has `jsonrpc`, `id` (an integer or a string), `method` and optional \
         `params`. A notification has no `id`. A response has the request's `id` and one of \
         `result` or `error`, never both.\n\
         - `params` is always an object; absent means `{}`.\n\
         - Ids are unique per sender while outstanding; the host counts from 1.\n\
         - Unknown fields are ignored. An unknown request is answered -32601; an unknown \
         notification is ignored.\n\
         - Names are `snake_case`; methods are `area/verb_noun`; names starting `rpc.` are \
         never used.\n",
    );

    out.push_str("\n## Error codes\n\n");
    out.push_str(
        "`error.message` is one short sentence naming the cause only, meaning first. \
         `error.data` carries `kind` (the name below) and optionally `place`, `hint`, \
         `detail` and `retry_after_ms`. The host builds the owner's line, \"Could not VERB \
         OBJECT: CAUSE. NEXT STEP.\", from them.\n\n",
    );
    out.push_str("| Code | Name | Meaning |\n|---|---|---|\n");
    for kind in ErrorKind::ALL {
        out.push_str(&format!(
            "| {} | `{}` | {} |\n",
            kind.code(),
            kind.name(),
            kind.meaning()
        ));
    }

    out.push_str("\n## Methods\n\n");
    out.push_str(
        "Each method says who sends it, whether it is answered, what allows it, and whether \
         alpha 2 serves it. A method marked \"shape only\" has its shape and fixtures fixed \
         now, so it is decided once, and the host serves it when the feature that needs it \
         arrives.\n",
    );
    for area in Area::ALL {
        out.push_str(&format!("\n### {}\n\n", area.title()));
        for m in ALL.iter().filter(|m| m.area == area) {
            out.push_str(&format!(
                "- `{}`: {}, {}. {} Allowed by: {}. State: {}.\n",
                m.name,
                m.sender.words(),
                m.call.words(),
                m.summary,
                m.gate,
                m.availability.words()
            ));
        }
    }

    out.push_str("\n## Index by direction\n\n");
    for (sender, heading) in [
        (methods::Sender::Host, "Host to plugin"),
        (methods::Sender::Plugin, "Plugin to host"),
        (methods::Sender::Either, "Either way"),
    ] {
        for call in [Call::Request, Call::Notification] {
            let names: Vec<&str> = ALL
                .iter()
                .filter(|m| m.sender == sender && m.call == call)
                .map(|m| m.name)
                .collect();
            if names.is_empty() {
                continue;
            }
            out.push_str(&format!(
                "{heading}, {}s ({}): {}.\n\n",
                call.words(),
                names.len(),
                names.join(", ")
            ));
        }
    }
    out.push_str(
        "Retired names, never used: config/get (settings come in initialize and \
         settings/changed), ui/progress (progress is $/progress) and hook/event (hooks are \
         hook/before and hook/after).\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_method_has_exactly_one_entry() {
        let text = page();
        for m in ALL {
            let entry = format!("- `{}`: ", m.name);
            let count = text.lines().filter(|l| l.starts_with(&entry)).count();
            assert_eq!(count, 1, "{}", m.name);
        }
        for retired in ["`config/get`", "`ui/progress`", "`hook/event`"] {
            assert!(!text.contains(retired), "{retired}");
        }
    }

    #[test]
    fn every_error_kind_is_in_the_table() {
        let text = page();
        for kind in ErrorKind::ALL {
            let row = format!("| {} | `{}` |", kind.code(), kind.name());
            assert!(text.contains(&row), "{row}");
        }
    }

    #[test]
    fn the_page_has_no_trailing_spaces_and_ends_with_a_line_break() {
        let text = page();
        assert!(text.ends_with('\n'));
        assert!(text.lines().all(|l| !l.ends_with(' ')));
    }
}
