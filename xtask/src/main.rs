//! The workspace's own tasks, run as `cargo xtask <task>`:
//!
//! - `deps --check`: every dependency comes from `[workspace.dependencies]`
//!   and every internal dependency points the allowed way
//!   (docs/dev/architecture.md).
//! - `regen [--check]`: lists what it will regenerate; does nothing yet.
//! - `keyboard [--check]`: writes `docs/keyboard.md` from the keymap's
//!   defaults, or checks that it is current.
//!
//! Later waves add `settings-doc`, `notices`, `icons`, `dist` and `bench`.

mod deps;
mod keyboard;
mod logo;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

use anyhow::{Result, bail};

const USAGE: &str = "Usage: cargo xtask deps --check | regen [--check] | keyboard [--check] | logo";

fn main() -> ExitCode {
    match run() {
        Ok(true) => ExitCode::SUCCESS,
        Ok(false) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("Could not run the task: {error:#}.");
            ExitCode::from(2)
        }
    }
}

/// The workspace's root folder: the parent of this crate's folder.
fn root() -> Result<PathBuf> {
    match Path::new(env!("CARGO_MANIFEST_DIR")).parent() {
        Some(root) => Ok(root.to_path_buf()),
        None => bail!("the workspace root could not be found"),
    }
}

fn run() -> Result<bool> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let args: Vec<&str> = args.iter().map(String::as_str).collect();
    let root = root()?;
    match args.as_slice() {
        ["deps", "--check"] | ["deps"] => deps::check(&root),
        ["regen"] | ["regen", "--check"] => {
            println!("regen: nothing is generated by regen yet. Later it rebuilds:");
            println!("docs/keyboard.md, written today by cargo xtask keyboard");
            println!("docs/settings-reference.md, from the settings schema (Wave 1)");
            println!("THIRD-PARTY-NOTICES.md, from cargo about (Wave 1)");
            Ok(true)
        }
        ["keyboard"] => keyboard::write(&root),
        ["keyboard", "--check"] => keyboard::check(&root),
        ["logo"] => logo::run(&root),
        _ => {
            eprintln!("{USAGE}");
            Ok(false)
        }
    }
}
