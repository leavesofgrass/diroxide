//! `cargo xtask keyboard`: writes `docs/keyboard.md` from the command
//! catalog, the keymap's defaults and the three key tables, as two lists:
//! the terminal's keys and the window's. The page is generated; nobody
//! edits it by hand. `cargo xtask regen` writes it too.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use diroxide_app::commands::{CATALOG, CommandInfo};
use diroxide_app::keymap::tables::{
    TerminalKind, reserved_table, screen_reader_table, terminal_entry, terminal_table,
};
use diroxide_app::keymap::{Keymap, Platform, written};
use diroxide_app::menu::{ItemAction, Menus};
use diroxide_core::{Key, KeyColumn, Layer};

/// The page, relative to the workspace root.
pub const PAGE: &str = "docs/keyboard.md";

/// The platform the page names keys for: Alt, not Option.
const NAMES: Platform = Platform::Windows;

fn layer_heading(layer: Layer) -> &'static str {
    match layer {
        Layer::Global => "Everywhere",
        Layer::Panel => "In a panel",
        Layer::List => "In any list",
        Layer::Viewer => "In the viewer",
        Layer::Preview => "In the preview",
        Layer::Dialog => "In a question",
    }
}

fn keys_of(keymap: &Keymap, info: &CommandInfo) -> Vec<Key> {
    keymap
        .bindings()
        .iter()
        .filter(|b| b.layer == info.layer && b.command == info.id)
        .map(|b| b.key)
        .collect()
}

fn line(keys: &[Key], info: &CommandInfo) -> String {
    let keys: Vec<String> = keys.iter().map(|k| written(k, NAMES)).collect();
    format!(
        "- {}: {}. {} ({})",
        keys.join(" or "),
        info.name,
        info.help,
        info.id
    )
}

fn column_section(page: &mut String, column: KeyColumn) {
    let keymap = Keymap::defaults_for(column);
    for layer in Layer::ALL {
        let lines: Vec<String> = CATALOG
            .iter()
            .filter(|info| info.layer == layer)
            .filter_map(|info| {
                let keys = keys_of(&keymap, info);
                (!keys.is_empty()).then(|| line(&keys, info))
            })
            .collect();
        if !lines.is_empty() {
            page.push_str(&format!("\n### {}\n\n", layer_heading(layer)));
            for l in lines {
                page.push_str(&l);
                page.push('\n');
            }
        }
    }
    let keyless: Vec<String> = CATALOG
        .iter()
        .filter(|info| keys_of(&keymap, info).is_empty())
        .map(|info| format!("- {}. {} ({})", info.name, info.help, info.id))
        .collect();
    if !keyless.is_empty() {
        page.push_str("\n### By the palette and the menus\n\n");
        for l in keyless {
            page.push_str(&l);
            page.push('\n');
        }
    }
}

fn capitalized(text: &str) -> String {
    let mut chars = text.chars();
    match chars.next() {
        Some(c) => c.to_uppercase().chain(chars).collect(),
        None => String::new(),
    }
}

/// The menu and item that reach a command, in words: "Edit menu, Paste".
fn sure_way(menus: &Menus, info: &CommandInfo) -> String {
    for menu in menus.menus() {
        if menu
            .items
            .iter()
            .any(|i| i.action == ItemAction::Command(info.id.clone()))
        {
            let parent = menus.bar().find(|bar| {
                bar.items
                    .iter()
                    .any(|i| i.action == ItemAction::Submenu(menu.id.clone()))
            });
            return match parent {
                Some(parent) => format!(
                    "{} menu, {} submenu, {}",
                    parent.title, menu.title, info.name
                ),
                None => format!("{} menu, {}", menu.title, info.name),
            };
        }
    }
    "the command palette".to_owned()
}

/// The page's text.
pub fn generate() -> String {
    let mut page = String::new();
    page.push_str("# Keyboard\n\n");
    page.push_str("This page is generated by `cargo xtask keyboard` from the command catalog, the keymap's defaults and the key tables. Do not edit it by hand; change the catalog or the tables instead.\n\n");
    page.push_str("Each line gives the key first, then the command, what it does, and its id in parentheses. A key is one key with its modifiers; there are no key sequences. Insert is never used, because it is the screen readers' key. Change any key in `keymap.toml` in the config folder; diroxide writes the built-in keys beside it as `keymap-defaults.toml`. The `single_letters` setting turns keys without Control or Alt off.\n\n");
    page.push_str("The command palette reaches every command by name: Ctrl+P in a terminal, Ctrl+Shift+P or Ctrl+P in the window. The menus are the sure way where a terminal does not pass a key: F9, or Alt with a menu's letter.\n");
    page.push_str("\n## In a terminal\n");
    column_section(&mut page, KeyColumn::Terminal);
    page.push_str("\n## In the window\n\n");
    page.push_str("The window arrives with alpha.6; these are its keys. On macOS the window uses Command where this list says Ctrl, and leaves Ctrl+F3 to Ctrl+F7 and Ctrl+Space to the system; the Sort list, the View menu and the palette sort there.\n");
    column_section(&mut page, KeyColumn::Window);

    let menus = Menus::builtin();
    let terminal = Keymap::defaults_for(KeyColumn::Terminal);
    page.push_str("\n## Keys a terminal may keep\n\n");
    page.push_str("These keys of the terminal list work in most terminals, but a terminal program may keep them or send another key. Each one's command is also in a menu, the sure way.\n\n");
    for info in CATALOG.iter() {
        for key in keys_of(&terminal, info) {
            let Some(row) = terminal_entry(&key) else {
                continue;
            };
            let who = match row.kind {
                TerminalKind::Program => format!("{} keeps it; {}", row.program, row.why),
                TerminalKind::Differs => capitalized(&row.why),
                TerminalKind::Unsafe => continue,
            };
            page.push_str(&format!(
                "- {} for {}: {}. Sure way: {}.\n",
                written(&key, NAMES),
                info.name,
                who,
                sure_way(&menus, info)
            ));
        }
    }
    page.push_str("\n## Keys never used in a terminal\n\n");
    for row in terminal_table()
        .iter()
        .filter(|r| r.kind == TerminalKind::Unsafe)
    {
        let mut names: Vec<String> = row.keys.iter().map(|k| written(k, NAMES)).collect();
        if let Some(pattern) = row.pattern {
            names.push(pattern.words().to_owned());
        }
        page.push_str(&format!("- {}: {}.\n", names.join(", "), row.why));
    }
    page.push_str("\n## Keys the screen readers keep\n\n");
    page.push_str("diroxide binds none of these. A keypad key works under a screen reader only with Num Lock on, so it is never a command's only key.\n\n");
    for row in screen_reader_table() {
        let named_for = row.platform.unwrap_or(NAMES);
        let mut names: Vec<String> = row.keys.iter().map(|k| written(k, named_for)).collect();
        if let Some(pattern) = row.pattern {
            names.push(pattern.words().to_owned());
        }
        let platform = match row.platform {
            Some(Platform::MacOs) => " On macOS.",
            Some(Platform::Other) => " On Linux.",
            Some(Platform::Windows) => " On Windows.",
            None => "",
        };
        page.push_str(&format!(
            "- {}: {}, {}.{platform}\n",
            names.join(", "),
            row.readers,
            row.purpose
        ));
    }
    page.push_str("\n## Kept for later alphas\n\n");
    for row in reserved_table() {
        let names: Vec<String> = row.keys.iter().map(|k| written(k, NAMES)).collect();
        let column = match row.column {
            None => String::new(),
            Some(KeyColumn::Terminal) => ", in a terminal".to_owned(),
            Some(KeyColumn::Window) => ", in the window".to_owned(),
        };
        page.push_str(&format!(
            "- {}: {}, coming in {}{column}.\n",
            names.join(" or "),
            row.name,
            row.alpha
        ));
    }
    page.push_str("\n## See also\n\n- [Settings reference](settings-reference.md)\n- [The documentation index](README.md)\n");
    page
}

/// Writes the page.
pub fn write(root: &Path) -> Result<bool> {
    let path = root.join(PAGE);
    fs::write(&path, generate()).with_context(|| format!("{PAGE} could not be written"))?;
    println!("keyboard: wrote {PAGE}.");
    Ok(true)
}

/// Checks that the page on disk is the generated one.
pub fn check(root: &Path) -> Result<bool> {
    let on_disk = fs::read_to_string(root.join(PAGE)).unwrap_or_default();
    if on_disk == generate() {
        println!("keyboard: Pass. {PAGE} is current.");
        Ok(true)
    } else {
        println!("keyboard: Fail. {PAGE} is out of date; run cargo xtask keyboard.");
        Ok(false)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_page_puts_keys_first_and_names_every_command() {
        let page = generate();
        assert!(page.contains("\n- F5: Copy to other panel. "));
        assert!(page.contains("\n- Ctrl+Q: Quit. Leaves diroxide. (app.quit)\n"));
        assert!(page.contains("\n## In a terminal\n"));
        assert!(page.contains("\n## In the window\n"));
        assert!(page.contains("\n### In any list\n"));
        assert!(page.contains("- Ctrl+V for Paste: Windows Terminal keeps it"));
        assert!(page.contains("Sure way: Edit menu, Paste."));
        assert!(page.contains("Sure way: View menu, Sort submenu, Sort by modified."));
        assert!(page.contains("- Ctrl+F: Find files, coming in alpha.3.\n"));
        for info in CATALOG.iter() {
            assert!(page.contains(&format!("({})", info.id)), "{}", info.id);
        }
        assert!(!page.contains('|'), "no tables in user docs");
        assert!(page.contains("\n## See also\n"));
    }
}
