//! `cargo xtask keyboard`: writes `docs/keyboard.md` from the keymap's
//! defaults and the command catalog. The page is generated; nobody edits
//! it by hand.

use std::fs;
use std::path::Path;

use anyhow::{Context, Result};
use diroxide_app::{CATALOG, Keymap};
use diroxide_core::Layer;

const PAGE: &str = "docs/keyboard.md";

fn layer_heading(layer: Layer) -> &'static str {
    match layer {
        Layer::Global => "Everywhere",
        Layer::Panel => "In a panel",
        Layer::List => "In any list",
        Layer::Viewer => "In the viewer",
        Layer::Dialog => "In a dialog",
    }
}

/// The page's text.
pub fn generate() -> String {
    let keymap = Keymap::defaults();
    let mut page = String::new();
    page.push_str("# Keyboard\n\n");
    page.push_str("This page is generated by `cargo xtask keyboard` from the keymap's defaults. Do not edit it by hand; change the command catalog or the keymap instead.\n\n");
    page.push_str("Each line gives the key first, then the command and what it does. Two keys separated by a space are pressed one after the other. Insert is never used, because it is the NVDA and JAWS key. Keys can be changed in `keymap.toml`, and single-letter keys can be turned off.\n");
    for layer in [
        Layer::Global,
        Layer::Panel,
        Layer::List,
        Layer::Viewer,
        Layer::Dialog,
    ] {
        let mut lines = Vec::new();
        for info in &CATALOG {
            let keys: Vec<String> = keymap
                .bindings()
                .iter()
                .filter(|b| b.layer == layer && b.command == info.id)
                .map(|b| b.chord.to_string())
                .collect();
            if !keys.is_empty() {
                lines.push(format!(
                    "- {}: {}. {}",
                    keys.join(" or "),
                    info.name,
                    info.help
                ));
            }
        }
        if !lines.is_empty() {
            page.push_str(&format!("\n## {}\n\n", layer_heading(layer)));
            for line in lines {
                page.push_str(&line);
                page.push('\n');
            }
        }
    }
    page.push_str("\n## See also\n\n- [The documentation index](README.md)\n");
    page
}

/// Writes the page.
pub fn write(root: &Path) -> Result<bool> {
    let path = root.join(PAGE);
    fs::write(&path, generate()).with_context(|| format!("{PAGE} could not be written"))?;
    println!("keyboard: wrote {PAGE}.");
    Ok(true)
}

/// Checks that the page on disk is the generated one.
pub fn check(root: &Path) -> Result<bool> {
    let on_disk = fs::read_to_string(root.join(PAGE)).unwrap_or_default();
    if on_disk == generate() {
        println!("keyboard: Pass. {PAGE} is current.");
        Ok(true)
    } else {
        println!("keyboard: Fail. {PAGE} is out of date; run cargo xtask keyboard.");
        Ok(false)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_page_puts_keys_first() {
        let page = generate();
        assert!(page.contains("\n- F5: Copy to other panel. "));
        assert!(page.contains("\n- Ctrl+Q or F10: Quit. Leaves diroxide.\n"));
        assert!(page.contains("\n## In any list\n"));
        assert!(!page.contains('|'), "no tables in user docs");
    }
}
