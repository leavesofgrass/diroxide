//! The protocol reference, `docs/dev/plugin-protocol.md`, generated from
//! [`super::methods::ALL`] and [`super::ErrorKind::ALL`]. `cargo xtask
//! regen` writes it and `cargo xtask regen --check` checks it; nobody
//! edits it by hand.

use super::methods::{self, ALL, Area, Call};
use super::{ErrorKind, MAX_LINE_BYTES, MAX_LINE_BYTES_LIMIT, PROTOCOL};

/// The page, relative to the workspace root.
pub const PAGE: &str = "docs/dev/plugin-protocol.md";

/// The page's text.
pub fn page() -> String {
    let (requests, notifications) = methods::counts();
    let mut out = String::new();
    out.push_str("# Plugin protocol reference\n\n");
    out.push_str(
        "This page is generated by `cargo xtask regen` from the methods module of \
         `diroxide-plugins` (`protocol::methods`). Do not edit it by hand; change the \
         module instead. The reasons behind each rule are in ADR-0006 and in the plan, \
         section 5.8.\n\n",
    );
    out.push_str(&format!(
        "Protocol {PROTOCOL} has {requests} requests and {notifications} notifications. \
         Within protocol {PROTOCOL} only additions are made, and every method is optional: \
         a host method the plugin did not declare in its manifest and confirm in \
         `initialize` is never called, and a service the host did not offer in \
         `host_capabilities` is never called by the plugin.\n"
    ));

    out.push_str("\n## Framing\n\n");
    out.push_str(
        "- One JSON-RPC 2.0 message per line, UTF-8 without a byte order mark, in both \
         directions. The host ends lines with `\\n` and accepts `\\r\\n`.\n",
    );
    out.push_str(&format!(
        "- The longest line is {} MiB by default; a plugin may ask for up to {} MiB in its \
         manifest. The reader enforces the limit while reading; a longer line is refused, \
         and the next line is still read.\n",
        MAX_LINE_BYTES / (1024 * 1024),
        MAX_LINE_BYTES_LIMIT / (1024 * 1024)
    ));
    out.push_str(
        "- A line that does not start with `{` or `[` after spaces is stray output: \
         logged, counted and never answered. A line that starts with `{` and does not \
         parse, or is \
         not valid UTF-8, is answered with -32700 and a null id.\n",
    );
    out.push_str("- Batches (JSON arrays) are refused with -32600.\n");
    out.push_str(
        "- Standard error is free text for the plugin's log, never the screen.\n\
         - A plugin flushes after every message.\n",
    );

    out.push_str("\n## Envelopes\n\n");
    out.push_str(
        "- A request has `jsonrpc`, `id` (an integer or a string), `method` and optional \
         `params`. A notification has no `id`. A response has the request's `id` and one of \
         `result` or `error`, never both.\n\
         - `params` is always an object; absent means `{}`.\n\
         - Ids are unique per sender while outstanding; the host counts from 1.\n\
         - Unknown fields are ignored. An unknown request is answered -32601; an unknown \
         notification is ignored.\n\
         - Names are `snake_case`; methods are `area/verb_noun`; names starting `rpc.` are \
         never used.\n",
    );

    out.push_str("\n## Error codes\n\n");
    out.push_str(
        "`error.message` is one short sentence naming the cause only, meaning first. \
         `error.data` carries `kind` (the name below) and optionally `place`, `hint`, \
         `detail` and `retry_after_ms`. The host builds the owner's line, \"Could not VERB \
         OBJECT: CAUSE. NEXT STEP.\", from them.\n\n",
    );
    out.push_str("| Code | Name | Meaning |\n|---|---|---|\n");
    for kind in ErrorKind::ALL {
        out.push_str(&format!(
            "| {} | `{}` | {} |\n",
            kind.code(),
            kind.name(),
            kind.meaning()
        ));
    }

    out.push_str("\n## Methods\n\n");
    out.push_str(
        "Each method says who sends it, whether it is answered, what allows it, and whether \
         alpha 2 serves it. A method marked \"shape only\" has its shape and fixtures fixed \
         now, so it is decided once, and the host serves it when the feature that needs it \
         arrives.\n",
    );
    for area in Area::ALL {
        out.push_str(&format!("\n### {}\n\n", area.title()));
        for m in ALL.iter().filter(|m| m.area == area) {
            out.push_str(&format!(
                "- `{}`: {}, {}. {} Allowed by: {}. State: {}.\n",
                m.name,
                m.sender.words(),
                m.call.words(),
                m.summary,
                m.gate,
                m.availability.words()
            ));
        }
    }

    out.push_str("\n## Additions of alpha 4\n\n");
    out.push_str(
        "Additions within protocol 1, fixed by alpha 4's contract step so the lanes that serve \
         them change no shape.\n\n\
         - `tools/run` takes `split` as `\"lines\"` (the default, at each line feed), `\"nul\"` \
         (at each NUL) or `\"cr\"` (at each line feed and each carriage return, so a progress \
         line a program rewrites in place, such as git's `clone --progress`, arrives as each \
         rewrite; the empty record between a CR and its LF is dropped).\n\
         - A `[[provider]]` table takes `extensions`, the containers it claims inside archive \
         places (disk images such as `.iso`, the 7z tool's formats such as `.rar`, raw images \
         such as `.img`; never a format diroxide reads itself): a place such as \
         `fedora.iso!EFI/` reaches the plugin, which opens each container once, and reads a \
         container inside an archive through `fs/read`. It also takes `wants`, tools it uses \
         when they are there and works without, which Settings names and nothing turns \
         off.\n\
         - For `ui/form`, the app's side is `HostServices::form`, from a `Form` to a `FormAnswer` \
         (`{\"values\": {\"ID\": VALUE}}` or `{\"cancelled\": true}`), fields of kind text, \
         multiline, choice, checkbox, path and secret. Served since alpha 4: the app shows a \
         list of setting rows, the default button's row first, then one row a field, its label \
         first and its value after (\"Message: empty\", \"Sign-off: off\", \"Password: \
         hidden\"); a multiline field answers its lines joined by line feeds, and Escape answers \
         `{\"cancelled\": true}`.\n\
         - For `ui/show_diff`, the app's side is `HostServices::show_diff`, two documents in the \
         compare screens. Served since alpha 4: the same screens as two files, in the same \
         order (the verdict and counts, the direction, what was ignored, the files' facts, the \
         change list, one change in full, the unified view, Swap), named by the two documents' \
         titles, the view's title said last; a text with a NUL or many control characters is \
         compared byte by byte; a document has no place, so the viewer does not open on it.\n\
         - For `place/describe`, the app calls `Host::describe_place` off the input thread for a \
         folder a `[[place_info]]` matches; the answer's `text` is the title line's words. Called \
         since alpha 4: when a panel lands in a folder whose scheme fits and whose marker is in \
         it or a folder above it, the enabled plugins are asked in turn and the first words \
         win; the title line says them after the panel, cut at 40 characters, the plugin's \
         name last (\"repo, left panel, main, no upstream, 2 changed here (Git), in D:\\work\"); \
         the old title stays until the answer; the words are kept for the folder until it is \
         listed again (a reload, a change the folder's watch sees, a job's end) or the plugin \
         fails or is turned off; a plugin whose manifest declares no `[[place_info]]` is never \
         asked.\n\
         - For `column/format`, file panels call `Host::plugin_columns` for the columns enabled \
         plugins declare, keyed `PLUGIN.COLUMN`, and `Host::column_page` for a page of cells, \
         \"pending\" where unanswered and \"unavailable: plugin stopped\" when the plugin \
         cannot answer.\n\
         - `fs/stage` takes `{\"place\": OUTPUT}`, a file the plugin is about to create in a \
         folder on this computer, its name free and portable, and answers `{\"stage\": ID, \
         \"path\": PATH}`: a `.diro-part-` name with eight hexadecimal digits and the output's \
         extension in the output's folder, where the engine's own jobs stage, which the arrival \
         tracker and hot folders ignore. The plugin writes the whole output to `PATH` itself. At \
         most 64 stages are open at once. Served since alpha 4.\n\
         - `fs/commit` takes `{\"stage\": ID}` and moves the staged file into place with the \
         rename that never replaces; a name taken meanwhile is numbered as copies are \
         (\"report.pdf (2).age\"). It answers `{\"committed\": true, \"place\": PLACE, \"name\": \
         NAME}`, and the app records the file as made by the plugin's running command, so Undo \
         puts it in the trash (`HostServices::committed`). A stage that holds no plain file is \
         refused; a stage never committed is removed when the plugin's session ends. Served \
         since alpha 4.\n",
    );

    out.push_str("\n## Index by direction\n\n");
    for (sender, heading) in [
        (methods::Sender::Host, "Host to plugin"),
        (methods::Sender::Plugin, "Plugin to host"),
        (methods::Sender::Either, "Either way"),
    ] {
        for call in [Call::Request, Call::Notification] {
            let names: Vec<&str> = ALL
                .iter()
                .filter(|m| m.sender == sender && m.call == call)
                .map(|m| m.name)
                .collect();
            if names.is_empty() {
                continue;
            }
            out.push_str(&format!(
                "{heading}, {}s ({}): {}.\n\n",
                call.words(),
                names.len(),
                names.join(", ")
            ));
        }
    }
    out.push_str(
        "Retired names, never used: config/get (settings come in initialize and \
         settings/changed), ui/progress (progress is $/progress) and hook/event (hooks are \
         hook/before and hook/after).\n",
    );
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_method_has_exactly_one_entry() {
        let text = page();
        for m in ALL {
            let entry = format!("- `{}`: ", m.name);
            let count = text.lines().filter(|l| l.starts_with(&entry)).count();
            assert_eq!(count, 1, "{}", m.name);
        }
        for retired in ["`config/get`", "`ui/progress`", "`hook/event`"] {
            assert!(!text.contains(retired), "{retired}");
        }
    }

    #[test]
    fn every_error_kind_is_in_the_table() {
        let text = page();
        for kind in ErrorKind::ALL {
            let row = format!("| {} | `{}` |", kind.code(), kind.name());
            assert!(text.contains(&row), "{row}");
        }
    }

    #[test]
    fn the_page_has_no_trailing_spaces_and_ends_with_a_line_break() {
        let text = page();
        assert!(text.ends_with('\n'));
        assert!(text.lines().all(|l| !l.ends_with(' ')));
    }
}
